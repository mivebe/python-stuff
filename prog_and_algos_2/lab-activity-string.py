# Задача №4. Брой думи
# Програмата прочита текст, който може да съдържа:
# — малки и главни латински букви;
# — интервали;
# — препинателни знаци: точка, запетая, удивителен и въпросителен знак;
# — символ –, който в някои случаи означава тире, а в други — дефис.
# Дума — това е последователност от латински букви и знаци дефис, ограниченая от двата края.
# Като ограничители се приемат начало на ред, край на ред строки, интервал, препинателен знак и тире.
# Тирето се отличава от дефиса по това, че отляво и отдясно на знака дефис се пишат букви, а поне от 
# едната страна на тирето има или начало на ред, или край на ред, или интервал, или пррепинателен знак, или още едно тире.
# Напишете програма, определяща, колко са думите в даден ред от текста.
# Вход
# На единствения ред на стандартния вход се въвежда низ с неповече от 200 знака.
# Изход
# На стандартния изход изведете едно число — броя думи, които се съдържат във въведения текст.
# Примери
# Вход	Изход
# Hello , world!	2
# www.olympiads.ru	3
# Gyro-compass – this is a ...	4

text = input()
n = len(text)

is_dash = [False] * n
for i, char in enumerate(text):
    if char == '-':
        left_is_letter = i > 0 and text[i-1].isalpha()
        right_is_letter = i < n-1 and text[i+1].isalpha()
        if not (left_is_letter and right_is_letter):
            is_dash[i] = True

words = []
current_word = ""
for i, char in enumerate(text):
    if char.isalpha() or (char == '-' and not is_dash[i]):
        current_word += char
    else:
        if current_word:
            words.append(current_word)
            current_word = ""
if current_word:
    words.append(current_word)

count = sum(1 for word in words if any(c.isalpha() for c in word))
print(count)


