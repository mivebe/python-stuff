# 4 зад. Да се състави програма, чрез която в двумерен масив, с брой колони А и брой редове B,
# се въвеждат псевдослучайни естествени числа от интервала [0..100]. А и В се въвеждат от клавиатурата. 
# Програмата да въведе в два други едномерни масива, поотделно само четните и нечетни въведени числа.
# Чрез функция да се изведе броя на четните и нечетни числа.
# Пример: A=5; B=6 Изход: 
# 89; 9; 5; 94; 52; 56;
# 48; 36; 62; 87; 11; 85;
# 20; 8; 47; 17; 5; 60;
# 92; 46; 26; 60; 57; 2;
# 36; 76; 38; 25; 12; 62;
# 19 четни числа: 94; 52; 56; 48; 36; 62; 20; 8; 60; 92; 46; 26; 60; 2; 36; 76; 38; 12; 62;
# 11 нечетни числа: 89; 9; 5; 87; 11; 85; 47; 17; 5; 57; 25;

import random


def print_count(even, odd):
    print(f"{len(even)} четни числа: {'; '.join(map(str, even))};")
    print(f"{len(odd)} нечетни числа: {'; '.join(map(str, odd))};")


A = int(input("Въведете брой колони (A): "))
B = int(input("Въведете брой редове (B): "))

matrix = []
for i in range(B):
    row = []
    for j in range(A):
        row.append(random.randint(0, 100))
    matrix.append(row)

for row in matrix:
    print("; ".join(map(str, row)) + ";")

even = []
odd = []

for row in matrix:
    for num in row:
        if num % 2 == 0:
            even.append(num)
        else:
            odd.append(num)

print_count(even, odd)

# 5 зад. Организирана е среща на високо ниво. В една от залите има въртящ се бар, като всеки може да завърти плота и в двете посоки.
# Да се състави програма, която по въведени брой позиции в бара [5..20], текуща позиция на клиента и позиция на желана напитка се избира най-късия път в кръга.
# Вход:
# 16 2 14
# Изход:
# 4

# Обяснение на примера: общ брой позиции 16, текуща 2, желана 14. Изход: плота се върти 4 позиции.

n, current, desired = map(int, input().split())

direct = abs(desired - current)
shortest = min(direct, n - direct)

print(shortest)
