# 2 зад. На поредния световен конгрес на сумистите се събрали няколко тона спортисти.
# Да се състави програма (C++), чрез която по въведено общо тегло на сумисти и тяхното средно тегло се изчислява възможния брой спортисти.
# Програмата да дава възможност потребителят да тества различни входни данни. Броят на опитите се определя от потребителя.
# Общото тегло, в тонове, е естествено число от интервала [10..99]., а средното тегло, в килограми, е реално число от интервала [120.299].
# Вход:
# 14 130
# Изход:
# 108
# Обяснение на примера: 14 тона,  130 килограма тежи средно един сумист.

import math

attempts = int(input("Въведете брой опити: "))

for _ in range(attempts):
    while True:
        total_tons, avg_weight_kg = map(float, input("Въведете общо тегло (тонове) и средно тегло (кг): ").split())

        if not (10 <= total_tons <= 99):
            print("Грешка: Общото тегло трябва да е в интервала [10..99] тона.")
            continue
        if not (120 <= avg_weight_kg <= 299):
            print("Грешка: Средното тегло трябва да е в интервала [120..299] кг.")
            continue
        break

    total_kg = total_tons * 1000

    num_athletes = math.ceil(total_kg / avg_weight_kg)

    print(num_athletes)


