# резултата от текущ контрол в проценти и теглото му, както и резултата от финалния изпит в проценти и теглото му.
# Пресметнете крайния резултат по формулата:
# краен резултат = текущ контрол * тегло на текущ контрол + финален изпит * тегло на финален изпит
# Изведете името на студента, студентския номер и крайния резултат.
