# Условие:
# Да се състави програма, чрез която се въвеждат цели числа от интервала [1,100] в двумерен масив с брой редове n и брой стълбове m, където m и n може да не са равни.
# Програмата трябва да намери средната стойност по стълбове на двумерния масив и сложи резултата в едномерен масив.
# Пример:
# Вход:
# Въведете брой на редове и стълбове: 3 4
# Ред 1: 16 3 11 2
# Ред 2: 5 10 15 6
# Ред 3: 9 17 4 91
# Изход:
# Средна стойност по стълбове: 10.0 10.0 10.0 33.0
#
# Автор: [Михаил Бъжев]
# Факултетен номер: [223010031]
# Дата: 06.06.2025

# Въвеждане на размерите на масива
n, m = map(int, input("Въведете брой на редове и стълбове: ").split())

# Създаване и попълване на двумерния масив
matrix = []
for i in range(n):
    row = list(map(int, input(f"Ред {i+1}: ").split()))
    matrix.append(row)

# Изчисляване на средната стойност по стълбове
averages = []
for col in range(m):
    col_sum = 0
    for row in range(n):
        col_sum += matrix[row][col]
    averages.append(col_sum / n)

# Отпечатване на резултата
print("Средна стойност по стълбове:", ' '.join(f"{avg:.1f}" for avg in averages))