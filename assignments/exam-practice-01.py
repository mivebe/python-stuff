import math

# Въвеждане на диаметъра от потребителя
diameter = float(input("Въведете диаметъра на кръга: "))

# Изчисляване на радиуса
radius = diameter / 2

# Изчисляване на лицето и обиколката
area = math.pi * radius ** 2
circumference = math.pi * diameter

# Извеждане на резултатите
print(f"Лицето на кръга е: {area:.2f}")
print(f"Обиколката на кръга е: {circumference:.2f}")